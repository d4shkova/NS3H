/**
 * Themes (§6.1 — "theme tokens must be swappable later").
 *
 * A theme carries both halves: the app's design tokens and the terminal's palette.
 * Keeping them in one object is what stops the chrome and the session output drifting
 * apart — a light chrome with a black terminal looks like a bug.
 *
 * The palettes are NS3H's own renderings of well-known colour schemes, not copies of
 * any particular client's assets.
 */

export interface ThemeTokens {
  bgBase: string;
  bgPanel: string;
  bgElevated: string;
  bgHover: string;
  border: string;
  borderFocus: string;
  textPrimary: string;
  textSecondary: string;
  textTertiary: string;
  accent: string;
  accentHover: string;
  accentMuted: string;
  statusOk: string;
  statusWarn: string;
  statusError: string;
}

export interface TerminalPalette {
  background: string;
  foreground: string;
  cursor: string;
  selectionBackground: string;
  black: string;
  red: string;
  green: string;
  yellow: string;
  blue: string;
  magenta: string;
  cyan: string;
  white: string;
  brightBlack: string;
  brightRed: string;
  brightGreen: string;
  brightYellow: string;
  brightBlue: string;
  brightMagenta: string;
  brightCyan: string;
  brightWhite: string;
}

export interface ThemeDefinition {
  id: string;
  name: string;
  mode: 'dark' | 'light';
  tokens: ThemeTokens;
  terminal: TerminalPalette;
}

